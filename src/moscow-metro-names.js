function stationNameKey(name) {
  return String(name ?? "")
    .normalize("NFKC")
    .replace(/['’]/g, "")
    .toLocaleLowerCase("en-US")
    .replace(/[^\p{Letter}\p{Number}]+/gu, "-")
    .replace(/^-+|-+$/g, "");
}

const englishNameByStationKey = new Map(
  stationEntries.flatMap(([russianName, englishName]) => [
    [stationNameKey(russianName), englishName],
    [stationNameKey(englishName), englishName],
  ]),
);

export function getMoscowMetroEnglishName(name) {
  return englishNameByStationKey.get(stationNameKey(name));
}

